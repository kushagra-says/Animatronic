"""
evidence.py

Defines the evidence objects produced by the Feature Extraction layer.

Evidence represents objective information extracted from the input.
No reasoning or interpretation happens here.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Any


# ==========================================================
# Base Evidence
# ==========================================================

@dataclass
class Evidence:
    """
    Base class for all evidence generated by feature extractors.
    """

    # Feature extraction module
    extractor: str

    # Underlying model information
    model: str
    version: str

    # Confidence reported by the extractor
    confidence: float

    # Time when the evidence was generated
    timestamp: datetime


# ==========================================================
# Language Evidence
# ==========================================================

@dataclass
class LanguageEvidence(Evidence):
    """
    Evidence produced by the language detector.
    """

    language: str


# ==========================================================
# Entity Evidence
# ==========================================================

@dataclass
class EntityEvidence(Evidence):
    """
    Evidence produced by the entity extractor.
    """

    text: str

    label: str

    start: int

    end: int


# ==========================================================
# Semantic Evidence
# ==========================================================

@dataclass
class SemanticEvidence(Evidence):
    """
    Evidence produced by the semantic embedding model.
    """

    embedding: Any

    dimension: int